"""
evaluation/real_world/published_policies/live_verify.py

Emits a shell script that loads each real-world case (build_cases.py) into
LocalStack + Minikube and runs main.py, applying every lesson learned in
evaluation/generated_benchmark/'s live-sample rounds:
  - every policy document must carry "Version": "2012-10-17" (already true
    here -- these are the real, as-published documents)
  - use LocalStack's real default test account (000000000000), matching
    ACCOUNT in policies.py
  - each case resets LocalStack before it runs, so the 5 cases here never
    share an AWS account
  - ServiceAccount and role names here are already RFC 1123-safe hyphenated
    names (aws-load-balancer-controller, ebs-csi-controller-sa, etc. -- the
    projects' own recommended names)
  - the summary file is cleared at the start of every run (append-only
    otherwise)

Usage:
    python -m evaluation.real_world.published_policies.live_verify > /tmp/rwp_live.sh
    bash /tmp/rwp_live.sh
    cat evaluation/real_world/published_policies/live/summary.json
"""

from __future__ import annotations

import json

from evaluation.real_world.published_policies.build_cases import all_cases


def iam_role_cli(role):
    trust = json.dumps(role["AssumeRolePolicyDocument"])
    lines = [f"awslocal iam create-role --role-name {role['RoleName']} "
            f"--assume-role-policy-document '{trust}' >/dev/null"]
    for i, doc in enumerate(role.get("policy_documents", [])):
        pol = json.dumps(doc)
        lines.append(f"awslocal iam put-role-policy --role-name {role['RoleName']} "
                    f"--policy-name inline-{i} --policy-document '{pol}' >/dev/null")
    if role.get("is_admin"):
        lines.append(f"awslocal iam attach-role-policy --role-name {role['RoleName']} "
                     f"--policy-arn arn:aws:iam::aws:policy/AdministratorAccess >/dev/null")
    return lines


def case_script(case):
    lines = [f'echo "=== {case["case_id"]} ==="', "bash benchmarks/reset_environment.sh >/dev/null 2>&1"]
    for role in case["roles"]:
        lines += iam_role_cli(role)
    if case["entry_ns"] != "default":
        lines.append(f"kubectl create namespace {case['entry_ns']} --dry-run=client -o yaml | kubectl apply -f - >/dev/null")
    for sa, role_name in case["sa_role_map"].items():
        lines.append(f"kubectl create serviceaccount {sa} -n {case['entry_ns']} --dry-run=client -o yaml | kubectl apply -f - >/dev/null")
        role_arn = next(r["Arn"] for r in case["roles"] if r["RoleName"] == role_name)
        lines.append(f"kubectl annotate serviceaccount {sa} -n {case['entry_ns']} "
                     f"eks.amazonaws.com/role-arn={role_arn} --overwrite >/dev/null")
    out_json = f"evaluation/real_world/published_policies/live/{case['case_id']}.json"
    lines.append(f"python main.py --endpoint-url http://localhost:4566 --semantics strict "
                f"--output-json {out_json} > evaluation/real_world/published_policies/live/{case['case_id']}.log 2>&1")
    target = case["truth"].get("target")
    declared = case["truth"]["reachable"]
    entry_node = f"k8s:sa:{case['entry_ns']}:{case['entry_sa']}"
    lines.append(f"python -m evaluation.real_world.published_policies.check_live_case "
                f"{out_json} '{target}' {declared} '{case['case_id']}' '{entry_node}'")
    return lines


def main():
    cases = all_cases()
    print("#!/bin/bash")
    print("# Auto-generated by live_verify.py -- DO NOT EDIT BY HAND.")
    print(f"# {len(cases)} real-world cases (published policies + one Unit42-sourced pattern)")
    print("set -e")
    print("mkdir -p evaluation/real_world/published_policies/live")
    print("rm -f evaluation/real_world/published_policies/live/summary.jsonl evaluation/real_world/published_policies/live/summary.json")
    print('export AWS_DEFAULT_REGION=us-east-1 AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test')
    for c in cases.values():
        for line in case_script(c):
            print(line)
    print('echo "=== live verify complete: see evaluation/real_world/published_policies/live/summary.json ==="')
    print("python -m evaluation.real_world.published_policies.summarize_live")


if __name__ == "__main__":
    main()
